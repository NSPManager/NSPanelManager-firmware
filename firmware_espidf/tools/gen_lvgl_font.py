#!/usr/bin/env python3
"""
Generate a small LVGL 9 font (lv_font_fmt_txt, 4 bpp, no kerning) holding only
the given characters, rendered from a TTF with Pillow/FreeType.

Used for fonts where only a handful of glyphs are needed (logo text), so they
cost a few KB of flash instead of a full built-in font.

Example:
  python3 tools/gen_lvgl_font.py --font Montserrat-Regular.ttf --size 50 \
      --chars NSPAEL --name font_loading_logo_50 -o lib/Pages/fonts/font_loading_logo_50.c
"""
import argparse
import os

from PIL import Image, ImageDraw, ImageFont


def render_glyph(font, ch, size):
    # Render on a padded canvas with the pen at (origin_x, baseline_y) and crop
    # to the inked pixels: font.getbbox() returns the advance box, not the ink.
    origin_x, baseline_y = size, 2 * size
    canvas = Image.new("L", (3 * size, 3 * size), 0)
    ImageDraw.Draw(canvas).text((origin_x, baseline_y), ch, font=font, fill=255, anchor="ls")
    ink = canvas.getbbox()
    pixels = []
    box_w = box_h = left = bottom = 0
    if ink:
        x0, y0, x1, y1 = ink
        box_w, box_h = x1 - x0, y1 - y0
        left, bottom = x0 - origin_x, y1 - baseline_y
        img = canvas.crop(ink)
        pixels = [img.getpixel((x, y)) >> 4 for y in range(box_h) for x in range(box_w)]
    if len(pixels) % 2:
        pixels.append(0)
    packed = bytes((pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2))
    return {
        "char": ch,
        "bitmap": packed,
        "adv_w": round(font.getlength(ch) * 16),
        "box_w": box_w,
        "box_h": box_h,
        "ofs_x": left,
        "ofs_y": -bottom,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--font", required=True)
    parser.add_argument("--size", type=int, required=True)
    parser.add_argument("--chars", required=True)
    parser.add_argument("--name", required=True)
    parser.add_argument("-o", "--output", required=True)
    args = parser.parse_args()

    font = ImageFont.truetype(args.font, args.size)
    chars = sorted(set(args.chars))
    glyphs = [render_glyph(font, ch, args.size) for ch in chars]
    ascent, descent = font.getmetrics()
    cap_height = font.getbbox("H", anchor="ls")[3] - font.getbbox("H", anchor="ls")[1]
    x_height = font.getbbox("x", anchor="ls")[3] - font.getbbox("x", anchor="ls")[1]

    out = []
    out.append("/*******************************************************************************")
    out.append(f" * Size: {args.size} px, Bpp: 4, Characters: {''.join(chars)}")
    out.append(f" * Font: {os.path.basename(args.font)}")
    out.append(" * Generated by tools/gen_lvgl_font.py. Do not edit.")
    out.append(" ******************************************************************************/")
    out.append("")
    out.append('#include "lvgl.h"')
    out.append("")
    out.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    index = 0
    for g in glyphs:
        g["bitmap_index"] = index
        index += len(g["bitmap"])
        out.append(f'    /* U+{ord(g["char"]):04X} "{g["char"]}" */')
        data = g["bitmap"]
        for i in range(0, len(data), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    if index == 0:
        out.append("    0x00,")
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    out.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,")
    for g in glyphs:
        out.append(
            f'    {{.bitmap_index = {g["bitmap_index"]}, .adv_w = {g["adv_w"]}, .box_w = {g["box_w"]}, '
            f'.box_h = {g["box_h"]}, .ofs_x = {g["ofs_x"]}, .ofs_y = {g["ofs_y"]}}} /* "{g["char"]}" */,'
        )
    out.append("};")
    out.append("")
    first = ord(chars[0])
    offsets = [ord(c) - first for c in chars]
    out.append("static const uint16_t unicode_list_0[] = {" + ", ".join(f"0x{o:x}" for o in offsets) + "};")
    out.append("")
    out.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    out.append(
        f"    {{.range_start = {first}, .range_length = {offsets[-1] + 1}, .glyph_id_start = 1, "
        f".unicode_list = unicode_list_0, .glyph_id_ofs_list = NULL, .list_length = {len(chars)}, "
        ".type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY},"
    )
    out.append("};")
    out.append("")
    out.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    out.append("    .glyph_bitmap = glyph_bitmap,")
    out.append("    .glyph_dsc = glyph_dsc,")
    out.append("    .cmaps = cmaps,")
    out.append("    .kern_dsc = NULL,")
    out.append("    .kern_scale = 0,")
    out.append("    .cmap_num = 1,")
    out.append("    .bpp = 4,")
    out.append("    .kern_classes = 0,")
    out.append("    .bitmap_format = 0,")
    out.append("};")
    out.append("")
    out.append(f"const lv_font_t {args.name} = {{")
    out.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    out.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    out.append(f"    .line_height = {ascent + descent},")
    out.append(f"    .base_line = {descent},")
    out.append("#if LV_VERSION_CHECK(9, 6, 0) || LVGL_VERSION_MAJOR >= 10")
    out.append(f"    .cap_height = {cap_height},")
    out.append(f"    .x_height = {x_height},")
    out.append("#endif")
    out.append("    .subpx = LV_FONT_SUBPX_NONE,")
    out.append(f"    .underline_position = {-max(1, args.size // 14)},")
    out.append(f"    .underline_thickness = {max(1, args.size // 14)},")
    out.append("    .static_bitmap = 1,")
    out.append("    .dsc = &font_dsc,")
    out.append("    .fallback = NULL,")
    out.append("    .user_data = NULL,")
    out.append("};")
    out.append("")

    with open(args.output, "w") as f:
        f.write("\n".join(out))
    print(f"{args.output}: {len(chars)} glyphs, {index} bitmap bytes, line height {ascent + descent}")


if __name__ == "__main__":
    main()
